def placement_points(placement, kills, total_players):  # Define how placement awards points
    # placement, kills, total_players -> int

    if placement == 0 or placement == -1:
        return 0  # This one either!

    else:
        if placement == 1:
            return 27
        elif placement == 2:
            return 23
        elif 3 <= placement <= 64:
            return 5
        else:
            return 0
        
